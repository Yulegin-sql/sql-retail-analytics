-- ЗАДАЧА: ускорить поиск по stock_code через индекс
--
-- РЕЗУЛЬТАТ:
--   До индекса: 5 ms (0,005s)
--   После индекса: 2 ms (0,002)
--   Ускорение: в 2,5 раза
--
-- ПРИМЕЧАНИЕ:
--   Индекс ускоряет select, но замедляет insert/update,
--   потому что при каждой вставке нужно обновлять сам индекс.
--   В нашем случае stock_code — это код товара, он редко меняется,
--   но по нему часто ищут, значит индекс оправдан.

-- ШАГ 1: медленный запрос (замер до индекса)
select * from retail 
where stock_code = '85123A';

-- ШАГ 2: создание индекса
create index idx_stock_code on retail(stock_code);

-- ШАГ 3: замер после индекса
select * from retail 
where stock_code = '85123A';